// Build-time replacement for runtime fs.existsSync: Cloudflare Workers have no filesystem,
// so the list of files under /public is baked into a module instead.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve("public");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(path.relative(root, full).split(path.sep).join("/"));
  }
})(root);
files.sort();

writeFileSync(
  path.resolve("src/lib/publicAssetManifest.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-public-manifest.mjs — do not edit.\nexport const PUBLIC_ASSETS: ReadonlySet<string> = new Set(${JSON.stringify(files, null, 2)});\n`,
);
console.log(`public asset manifest: ${files.length} files`);
